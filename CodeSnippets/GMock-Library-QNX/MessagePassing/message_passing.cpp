using namespace std;

#define FESTO1 true


#define USE_GNS true


#define ATTACH_POINT "server"
thread server;

int chid = 0;

std::mutex mut;
bool serverRunning = false;



void runServer(){

	system("gns -s");

	name_attach_t *attach;
	if(USE_GNS){
		if ((attach = name_attach(NULL, ATTACH_POINT, NAME_FLAG_ATTACH_GLOBAL)) == NULL) {  // important!! Use "NAME_FLAG_ATTACH_GLOBAL" flag if the other machine should see it !!!
		   perror("[Server] Failed to attach name!");
	    }
		std::cout << "[Server] Channel open with name: " << ATTACH_POINT << "\n";
		chid = attach->chid; // only for printing

	}else{
		if((chid = ChannelCreate(0)) < 0 ){
			perror("[Server] Failed to create channel!");
		}
	}



	mut.lock();
	serverRunning = true;
	mut.unlock();

	cout << "Receiving on channel: " << chid <<"\n";


	 while (1) {
		   // Waiting for a message and read first header
		   _pulse pulse;
		   int rcvid = MsgReceive (chid, &pulse, sizeof (_pulse), NULL);

	       if (rcvid == -1) { // Error occurred
	    	   perror("[Server]: MsgReceived failed!");
	           break;
	       }

	       if (rcvid == 0) {// Pulse was received
	    	   switch (pulse.code) {
	    	   	case _PULSE_CODE_DISCONNECT:
	    	   		printf("[Server] received _PULSE_CODE_DISCONNECT\n");
	    	   	    /* A client disconnected all its connections (called
	    	   	     * name_close() for each name_open() of our name) or
	    	   	     * terminated. */
	    	   	    ConnectDetach(pulse.scoid);
	    	   	    break;
	    	   	case _PULSE_CODE_UNBLOCK:
	    	   	    printf("[Server] received _PULSE_CODE_UNBLOCK\n");
	    	   	    /* REPLY blocked client wants to unblock (was hit by
	    	   	     * a signal or timed out).  It's up to you if you
	    	   	     * reply now or later. */
	    	   	    break;
	    	   	default:
	    	   	    /* A pulse sent by one of your processes or a
	    	   	     * _PULSE_CODE_COIDDEATH or _PULSE_CODE_THREADDEATH
	    	   	     * from the kernel? */
	    	   	     printf("[Server] Pulse Msg: %d\n",pulse.value);
	    	   	     break;
	    	   	}
	           continue;
	       }
	       // some sync msg was received
	       if ((_IO_BASE <= pulse.type) && (pulse.type <= _IO_MAX)) {
	    	   // Some QNX IO msg generated by gns was received

	    	   if (pulse.type == _IO_CONNECT ) {    // VERY IMPORTANT WHEN USING GNS
	    	   		// QNX IO msg _IO_CONNECT was received; answer with EOK
	    	   	    printf("[Server] received _IO_CONNECT (sync. msg) \n");
	    	   	    MsgReply( rcvid, EOK, NULL, 0 );
	    	   	}
	    	   continue;
	       }
	       //  A sync msg (presumable ours) was received; handle it
	      cout << "[SERVER] received" << endl;
	   }

	 if(USE_GNS){
		 if(name_detach(attach, 0) != 0){
			 perror("[Server] Failed to detach name!");
		 }
		 std::cout << "[Server] Successfully detached name and closed channel!\n";

	 }else{
		 if(ChannelDestroy(chid) != 0 ){
			 perror("[Server] Failed to destroy channel!");
		 }
	 }



}


int main() {

	if(FESTO1){

		server = thread(runServer);

	}else{

		system("gns -c");




		int conid;

		if(USE_GNS){
			if((conid = name_open(ATTACH_POINT,NAME_FLAG_ATTACH_GLOBAL)) < 0){   // important!! if server is running with "NAME_FLAG_ATTACH_GLOBAL" flag, you hae to use it here too
				perror("[Client] name_open failed");

			}
			std::cout << "[Client] Opened name and connected to channel\n";

		}else{
			if ((conid = ConnectAttach(0,0, chid,_NTO_SIDE_CHANNEL ,NAME_FLAG_ATTACH_GLOBAL)) < 0) {
				perror("[Client] ConnectAttach failed");
				return EXIT_FAILURE;
			}
		}


	//// ======== send pulse message ================

		 if(MsgSendPulse(conid,SIGEV_PULSE_PRIO_INHERIT,_PULSE_CODE_MINAVAIL+10,808) != 0){
			perror("[Client]: sendPulse failed");
			return EXIT_FAILURE;
		 }


	 //// ======== close connection ================

		 if(USE_GNS){

				if(name_close(conid) != 0){
					perror("[Client] name_close failed");
				}


			}else{
				// closes the connection to the server. Sends _PULSE_CODE_DISCONNECT to the server.
				if ((ConnectDetach(conid)) != 0) {
					perror("[Client] ConnectDetach failed");
					return EXIT_FAILURE;
				}
			}


	}
	while(1);

}
